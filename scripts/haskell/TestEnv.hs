-- Prints foundations' Test.env / Test.tenv / Test.datas as Lean source over de Bruijn terms,
-- so the Lean port is run on exactly the same definitions (nothing is translated by hand).
module TestEnv where
import qualified Test as T
import Syntax
import Type
import Prove
import Data.List

q :: String -> String
q s = "\"" ++ s ++ "\""

leanTerm :: [Var] -> Term -> String
leanTerm sc (Atm (Var v)) = case elemIndex v sc of
  Just i  -> "(.var " ++ show i ++ ")"
  Nothing -> "(.const " ++ q v ++ ")"
leanTerm _ (Atm (Con c)) = "(.con " ++ q c ++ ")"
leanTerm sc (App x y) = "(.app " ++ leanTerm sc x ++ " " ++ leanTerm sc y ++ ")"
leanTerm sc (Abs w b) = "(.abs " ++ leanTerm (w:sc) b ++ ")"
leanTerm sc (Cas x xs) = "(.cas " ++ leanTerm sc x ++ " " ++ alts xs ++ ")"
  where alts [] = ".nil"
        alts (((c, vs), b):r) = "(.alt " ++ q c ++ " " ++ show (length vs) ++ " " ++ leanTerm (reverse vs ++ sc) b ++ " " ++ alts r ++ ")"

leanTy :: Type -> String
leanTy (TAtm (TCon c)) = "(.con " ++ q c ++ ")"
leanTy (TAtm (TVar v)) = "(.var " ++ q v ++ ")"
leanTy (TBin TCom a b) = "(.com " ++ leanTy a ++ " " ++ leanTy b ++ ")"

atmTerm :: Term -> String
atmTerm (Atm (Var v)) = "Term.const " ++ q v
atmTerm (Atm (Con c)) = "Term.con " ++ q c

main :: IO ()
main = do
  putStrLn "import MathematicalMethodology.Strategic.Syntax\nimport MathematicalMethodology.Operational.Compute\n"
  putStrLn "/-!\n# foundations `Test.hs` environment\n"
  putStrLn "Generated by `scripts/haskell/TestEnv.hs` from foundations `Test.env`, `Test.tenv`\nand `Test.datas`; do not edit by hand.\n-/\n"
  putStrLn "namespace MM.Examples.TestEnv\n\nopen MM MM.Strategic\n"
  putStrLn "def datas : List DatasH :=\n  [" 
  putStrLn (intercalate ",\n" [ "    (" ++ q n ++ ", [" ++ intercalate ", " [ "(" ++ q c ++ ", [" ++ intercalate ", " (map leanTy fs) ++ "])" | (c, fs) <- cs ] ++ "])" | (n, cs) <- T.datas ])
  putStrLn "  ]\n"
  putStrLn "def env : Env :=\n  ["
  putStrLn (intercalate ",\n" [ "    (" ++ q v ++ ", " ++ leanTerm [] t ++ ")" | (Var v, t) <- T.env ])
  putStrLn "  ]\n"
  putStrLn "def tenv : TEnv :=\n  ["
  putStrLn (intercalate ",\n" [ "    (" ++ atmTerm e ++ ", " ++ leanTy t ++ ")" | (e, t) <- T.tenv ])
  putStrLn "  ]\n"
  putStrLn "end MM.Examples.TestEnv"
